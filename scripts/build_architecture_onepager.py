def build(out: Path) -> Path:
    GEN.mkdir(parents=True, exist_ok=True)
    bg = make_background(GEN / "background.png")
    frd_img = make_frd_preview(GEN / "frd_page.png")
    wb_img = make_workbook_preview(GEN / "sttm_sheet.png")
    shots = extract_screens(GEN)
    pick = shots.get("Select FRD — the corpus picker")
    review = shots.get("Results — ambiguity gate and human-in-the-loop review")
    if pick:
        pick = crop_to(pick, (0.15, 0.30, 0.85, 0.99), GEN / "shot_pick.png")
    if review:
        review = crop_to(review, (0.15, 0.05, 0.85, 0.74), GEN / "shot_review.png")
    # the raw extracted screenshots are scratch — keep only what the slide uses
    for p in shots.values():
        p.unlink(missing_ok=True)

    prs = Presentation()
    prs.slide_width, prs.slide_height = Inches(W_IN), Inches(H_IN)
    s = prs.slides.add_slide(prs.slide_layouts[6])
    s.shapes.add_picture(str(bg), 0, 0, prs.slide_width, prs.slide_height)
    for cx, cy in ((0.3, 0.3), (W_IN - 0.3, 0.3), (0.3, H_IN - 0.3), (W_IN - 0.3, H_IN - 0.3)):
        crosshair(s, cx, cy)

    # ----- header ------------------------------------------------------------
    label(s, 0.6, 0.42, 9, "Hexaware  ·  AmeriHealth Caritas  ·  AI-in-Engineering  ·  agent 01 / 03", color=G2)
    add_text(s, 0.6, 0.64, 9, 0.55, [("FRD → STTM Agent", {"color": WHITE, "bold": True, "size": 28}),
                                     ("    system architecture", {"color": G3, "size": 15})], size=28)
    add_text(s, 0.6, 1.16, 7.6, 0.3,
             [("An approved requirements document becomes an audited source-to-target mapping — "
               "every fact checked against the source text, every ambiguity routed to a person.", {})],
             size=11, color=G4)
    rows = [(0.7, [("read-only SharePoint", INDIGO, INDIGO_DIM), ("1 model call / document", CERULEAN, CERULEAN_DIM)]),
            (1.04, [("verdicts computed in code", TURQ, TURQ_DIM), ("human in the loop", GOLD, GOLD_DIM)])]
    for yy, row in rows:
        widths = [CHIP_CHAR * len(t) + CHIP_PAD for t, _, _ in row]
        cx = W_IN - 0.6 - sum(widths) - 0.1 * (len(row) - 1)
        for (t, col, bd), w in zip(row, widths):
            cx = chip(s, cx, yy, t, color=col, border=bd)

    # ----- band 1: the flow ----------------------------------------------------
    TOP, NH = 1.85, 1.95
    nodes = [  # x, w, accent, icon, idx, title, caption
        (0.6, 2.05, INDIGO, "folder", "SRC", "SharePoint library",
         "System of record. FRDs in, approved STTMs back. The agent only ever reads it."),
        (3.0, 2.05, TURQ, "refresh", "00", "Scheduled sync",
         "Every 15 min, incremental. Pairs each FRD with its STTM and indexes the corpus in Unity Catalog. Zero model calls."),
        (5.4, 3.15, TURQ, None, "01-04", "Generation job",
         "Four stages on Databricks. Extract is the single Claude call; parse, audit, gate and render are code."),
        (8.9, 2.05, GOLD, "user", "HITL", "Review app",
         "Pick an FRD, run, answer what the agent could not settle, re-render — then upload the approved STTM yourself."),
        (11.3, 1.45, INDIGO, "code", "OUT", "Outputs",
         "STTM workbook + feed contract → CodeGen and Code Review agents."),
    ]
    for x, w, acc, icon, idx, title, cap in nodes:
        add_rect(s, x, TOP, w, NH, fill=DG1, line=DG4, radius=0.04)
        add_dot(s, x + 0.24, TOP + 0.27, 0.1, acc)
        add_text(s, x + 0.4, TOP + 0.17, 0.9, 0.22, [(idx, {})], size=8.5, color=acc, font=MONO, spacing=1.4)
        add_text(s, x + 0.22, TOP + 0.42, w - 0.7, 0.3, [(title, {})], size=13, color=LG5, bold=True)
        if icon:
            add_icon(s, icon, x + w - 0.52, TOP + 0.17, 0.3)
        add_text(s, x + 0.22, TOP + 0.78, w - 0.4, NH - 0.9, [(cap, {})], size=9.5, color=G4, line_spacing=1.12)
    # the four stages inside the job node
    jx, jw = nodes[2][0], nodes[2][1]
    st = [("01", "Ingest", TURQ), ("02", "Extract", CERULEAN), ("03", "Audit · gate", TURQ), ("04", "Render", TURQ)]
    sgap = 0.1
    sw = (jw - 0.44 - 3 * sgap) / 4
    sy = TOP + NH - 0.62
    for i, (idx, name, acc) in enumerate(st):
        x = jx + 0.22 + i * (sw + sgap)
        add_rect(s, x, sy, sw, 0.42, fill=DG2, line=(CERULEAN_DIM if acc == CERULEAN else DG4), radius=0.12)
        add_text(s, x, sy + 0.06, sw, 0.15, [(idx, {})], size=7.5, color=acc, font=MONO, align=PP_ALIGN.CENTER)
        add_text(s, x, sy + 0.2, sw, 0.2, [(name, {})], size=8.5, color=(LG5 if acc == CERULEAN else G5),
                 bold=(acc == CERULEAN), align=PP_ALIGN.CENTER)
        if i < 3:
            add_line(s, x + sw + 0.01, sy + 0.21, x + sw + sgap - 0.01, sy + 0.21, color=G1, width=0.75, head=True)
    # connectors between nodes
    mid = TOP + 0.55
    for i in range(4):
        add_line(s, nodes[i][0] + nodes[i][1] + 0.02, mid, nodes[i + 1][0] - 0.02, mid, color=G2, width=1.0, head=True)
    # the human return loop

def rgb(h: str) -> RGBColor:
    return RGBColor.from_string(h.upper())


def _no_shadow(shape):
    spPr = shape._element.spPr
    spPr.append(spPr.makeelement(qn("a:effectLst"), {}))


def add_text(slide, x, y, w, h, runs, *, size=10, color=G5, font=SANS, bold=False,
             align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP, spacing=None, line_spacing=None):
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    tf.vertical_anchor = anchor
    paragraphs = runs
    if isinstance(runs, str):
        paragraphs = [[(runs, {})]]
    elif runs and not isinstance(runs[0], list):
        paragraphs = [runs]
    for pi, para in enumerate(paragraphs):
        p = tf.paragraphs[0] if pi == 0 else tf.add_paragraph()
        p.alignment = align
        if line_spacing:
            p.line_spacing = line_spacing
        for text, ov in para:
            r = p.add_run()
            r.text = text
            f = r.font
            f.name = ov.get("font", font)
            f.size = Pt(ov.get("size", size))
            f.bold = ov.get("bold", bold)
            f.color.rgb = rgb(ov.get("color", color))
            sp = ov.get("spacing", spacing)
            if sp is not None:
                r._r.get_or_add_rPr().set("spc", str(int(sp * 100)))
    return tb


def add_rect(slide, x, y, w, h, *, fill=DG1, line=DG4, line_w=0.75, radius=None):
    kind = MSO_SHAPE.ROUNDED_RECTANGLE if radius is not None else MSO_SHAPE.RECTANGLE
    s = slide.shapes.add_shape(kind, Inches(x), Inches(y), Inches(w), Inches(h))
    if radius is not None:
        s.adjustments[0] = radius
    if fill is None:
        s.fill.background()
    else:
        s.fill.solid()
        s.fill.fore_color.rgb = rgb(fill)
    if line is None:
        s.line.fill.background()
    else:
        s.line.color.rgb = rgb(line)
        s.line.width = Pt(line_w)
    _no_shadow(s)
    s.text_frame.text = ""
    return s


def add_line(slide, x1, y1, x2, y2, *, color=G1, width=0.75, head=False, dash=None):
    c = slide.shapes.add_connector(MSO_CONNECTOR.STRAIGHT, Inches(x1), Inches(y1), Inches(x2), Inches(y2))
    c.line.color.rgb = rgb(color)
    c.line.width = Pt(width)
    ln = c.line._get_or_add_ln()
    if dash:
        ln.append(ln.makeelement(qn("a:prstDash"), {"val": dash}))
    if head:
        ln.append(ln.makeelement(qn("a:tailEnd"), {"type": "triangle", "w": "sm", "len": "sm"}))
    return c


def add_dot(slide, cx, cy, d, color):
    s = slide.shapes.add_shape(MSO_SHAPE.OVAL, Inches(cx - d / 2), Inches(cy - d / 2), Inches(d), Inches(d))
    s.fill.solid()
    s.fill.fore_color.rgb = rgb(color)
    s.line.fill.background()
    _no_shadow(s)
    return s


def add_icon(slide, name, x, y, size):
    p = ICONS / f"{name}.png"
    if p.exists():
        slide.shapes.add_picture(str(p), Inches(x), Inches(y), Inches(size), Inches(size))


def add_image(slide, path, x, y, w, h):
    """Place an image scaled to FIT inside (w, h), centered — never distorted."""
    iw, ih = Image.open(path).size
    scale = min(w / iw, h / ih)
    pw, ph = iw * scale, ih * scale
    slide.shapes.add_picture(str(path), Inches(x + (w - pw) / 2), Inches(y + (h - ph) / 2), Inches(pw), Inches(ph))


def label(slide, x, y, w, text, *, color=G3, size=8, align=PP_ALIGN.LEFT):
    return add_text(slide, x, y, w, 0.22, [(text.upper(), {})], size=size, color=color, font=MONO,
                    spacing=1.6, align=align)


CHIP_CHAR, CHIP_PAD = 0.083, 0.34   # Courier New 7.5 pt + 1 pt tracking, measured in QA


def chip(slide, x, y, text, *, color=G4, border=DG5, size=7.5):
    w = CHIP_CHAR * len(text) + CHIP_PAD
    add_rect(slide, x, y, w, 0.26, fill=None, line=border, line_w=0.6, radius=0.5)
    add_text(slide, x, y + 0.055, w, 0.18, [(text.upper(), {})], size=size, color=color, font=MONO,
             spacing=1.0, align=PP_ALIGN.CENTER)
    return x + w + 0.1


def crosshair(slide, cx, cy, arm=0.07):
    add_line(slide, cx - arm, cy, cx + arm, cy, color=DG5, width=0.5)
    add_line(slide, cx, cy - arm, cx, cy + arm, color=DG5, width=0.5)



def make_frd_preview(path: Path) -> Path:
    """A page of the synthetic FRD; strict-grounded spans ({…}) underlined in
    cerulean — the fields 03 must find verbatim."""
    w, h = 1600, 780
    img = Image.new("RGB", (w, h), "#" + DG2)
    d = ImageDraw.Draw(img)
    d.rounded_rectangle([60, 40, w - 60, h + 40], radius=18, fill="#f6f7f9")
    fh, fs, fp, fm = _font("sans", 44, True), _font("sans", 30, True), _font("sans", 28), _font("mono", 24)
    y = 90
    for kind, text in FRD_LINES:
        x = 120
        if kind == "h":
            d.text((x, y), text, font=fh, fill="#1c2127"); y += 70
        elif kind == "m":
            d.text((x, y), text, font=fm, fill="#5f6b7c"); y += 56
        elif kind == "s":
            d.text((x, y), text, font=fs, fill="#215db0"); y += 52
        elif kind == "p":
            for part in re.split(r"(\{[^}]+\})", text):
                if not part:
                    continue
                strict = part.startswith("{")
                t = part.strip("{}")
                d.text((x, y), t, font=fp, fill="#1c2127")
                tw = d.textlength(t, font=fp)
                if strict:
                    d.line([x, y + 36, x + tw, y + 36], fill="#" + CERULEAN, width=4)
                x += tw
            y += 44
        else:
            y += 26
    fade = Image.new("L", (w, h), 0)
    fd = ImageDraw.Draw(fade)
    for i in range(140):
        fd.line([0, h - 140 + i, w, h - 140 + i], fill=int(255 * i / 140))
    img = Image.composite(Image.new("RGB", (w, h), "#" + DG2), img, fade)
    img.save(path, optimize=True)
    return path


